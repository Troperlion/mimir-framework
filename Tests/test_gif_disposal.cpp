#include "test_utils.hpp"
#include "stb_image.h"

int main() {
    // Red canvas, blue frame with disposal=3, then a transparent frame.
    // The third frame must restore red, including after output reallocations.
    const unsigned char gif[] = {
        0x47,0x49,0x46,0x38,0x39,0x61,0x02,0x00,0x01,0x00,0xf0,0x00,
        0x00,0xff,0x00,0x00,0xff,0xff,0xff,0x21,0xff,0x0b,0x4e,0x45,
        0x54,0x53,0x43,0x41,0x50,0x45,0x32,0x2e,0x30,0x03,0x01,0x02,
        0x00,0x00,0x21,0xf9,0x04,0x00,0x0c,0x00,0x00,0x00,0x2c,0x00,
        0x00,0x00,0x00,0x02,0x00,0x01,0x00,0x00,0x02,0x02,0x04,0x0a,
        0x00,0x21,0xf9,0x04,0x0c,0x22,0x00,0x00,0x00,0x2c,0x00,0x00,
        0x00,0x00,0x02,0x00,0x01,0x00,0x80,0x00,0x00,0xff,0xff,0xff,
        0xff,0x02,0x02,0x04,0x0a,0x00,0x21,0xf9,0x04,0x01,0x0c,0x00,
        0x00,0x00,0x2c,0x00,0x00,0x00,0x00,0x02,0x00,0x01,0x00,0x00,
        0x02,0x02,0x04,0x0a,0x00,0x3b,
    };
    for (int channels : {3, 4}) {
        int w = 0, h = 0, frames = 0, source_channels = 0;
        int* delays = nullptr;
        unsigned char* pixels = stbi_load_gif_from_memory(
            gif, sizeof(gif), &delays, &w, &h, &frames, &source_channels, channels);
        TASSERT_TRUE(pixels != nullptr);
        TASSERT_TRUE(w == 2 && h == 1 && frames == 3);
        bool correct = true;
        for (int frame = 0; frame < frames; ++frame) {
            for (int pixel = 0; pixel < w * h; ++pixel) {
                const auto* p = pixels + (frame * w * h + pixel) * channels;
                correct &= p[0] == (frame == 1 ? 0 : 255) && p[1] == 0 &&
                           p[2] == (frame == 1 ? 255 : 0);
                if (channels == 4) correct &= p[3] == 255;
            }
        }
        stbi_image_free(pixels);
        stbi_image_free(delays);
        TASSERT_TRUE(correct);
    }
    return 0;
}
